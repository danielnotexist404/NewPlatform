/**
 * Mock of POST /api/hooks/inflect (Part 03 §14 "התאמת הפנייה"): a small plural → female/male word map so the
 * card can show the adapted wording before the real endpoint exists. Words not in the map stay as they are.
 */
export type Address = "plural" | "female" | "male";

const MAP: Record<string, [female: string, male: string]> = {
  "לכם": ["לך", "לך"], "שלכם": ["שלך", "שלך"], "אתכם": ["אותך", "אותך"], "אתם": ["את", "אתה"], "ואתם": ["ואת", "ואתה"],
  "שאתם": ["שאת", "שאתה"], "תפסיקו": ["תפסיקי", "תפסיק"], "תבואו": ["תבואי", "תבוא"], "בואו": ["בואי", "בוא"],
  "קיבלתם": ["קיבלת", "קיבלת"], "מצאתם": ["מצאת", "מצאת"], "חזרתם": ["חזרת", "חזרת"], "הזמנתם": ["הזמנת", "הזמנת"],
  "משלמים": ["משלמת", "משלם"], "שואלים": ["שואלת", "שואל"], "מחפשים": ["מחפשת", "מחפש"], "ומחפשים": ["ומחפשת", "ומחפש"],
  "רוצים": ["רוצה", "רוצה"], "נחשו": ["נחשי", "נחש"], "תזמינו": ["תזמיני", "תזמין"], "שלחו": ["שלחי", "שלח"],
  "כתבו": ["כתבי", "כתוב"], "שמרו": ["שמרי", "שמור"], "בדקו": ["בדקי", "בדוק"], "לכו": ["לכי", "לך"], "יודעים": ["יודעת", "יודע"],
  "חושבים": ["חושבת", "חושב"], "צריכים": ["צריכה", "צריך"], "עושים": ["עושה", "עושה"], "אוהבים": ["אוהבת", "אוהב"],
};

export function inflect(text: string, to: Address): string {
  if (to === "plural") return text;
  const i = to === "female" ? 0 : 1;
  return text.replace(/[א-ת]+/g, (w) => (MAP[w] ? MAP[w][i] : w));
}
